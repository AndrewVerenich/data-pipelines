-- OLTP source of truth for A/B experiments.
-- Assignments are sticky SSOT; Debezium CDCs assignments + outcomes into Kafka.

CREATE TABLE experiments (
    experiment_id              INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    experiment_key             TEXT UNIQUE NOT NULL,
    name                       TEXT NOT NULL,
    status                     TEXT NOT NULL CHECK (status IN ('draft', 'running', 'stopped')),
    salt                       TEXT NOT NULL,
    traffic_pct                INT NOT NULL CHECK (traffic_pct BETWEEN 0 AND 100),
    attribution_window_seconds INT NOT NULL DEFAULT 3600,
    started_at                 TIMESTAMPTZ,
    stopped_at                 TIMESTAMPTZ,
    created_at                 TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE variants (
    variant_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    experiment_id INT NOT NULL REFERENCES experiments (experiment_id) ON DELETE CASCADE,
    variant_key   TEXT NOT NULL,
    weight        INT NOT NULL CHECK (weight > 0),
    UNIQUE (experiment_id, variant_key)
);

CREATE TABLE metrics (
    metric_id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    experiment_id    INT NOT NULL REFERENCES experiments (experiment_id) ON DELETE CASCADE,
    metric_key       TEXT NOT NULL,
    metric_type      TEXT NOT NULL CHECK (metric_type IN ('binomial', 'continuous')),
    role             TEXT NOT NULL CHECK (role IN ('primary', 'secondary', 'guardrail')),
    min_effect       DOUBLE PRECISION NOT NULL,
    higher_is_better BOOLEAN NOT NULL,
    UNIQUE (experiment_id, metric_key)
);

-- Sticky assignment = exposure. One row per (experiment, user).
CREATE TABLE assignments (
    assignment_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    experiment_id  INT NOT NULL REFERENCES experiments (experiment_id),
    experiment_key TEXT NOT NULL,
    user_id        TEXT NOT NULL,
    variant_key    TEXT NOT NULL,
    bucket         INT NOT NULL,
    assigned_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (experiment_id, user_id)
);

CREATE TABLE outcomes (
    event_id       TEXT PRIMARY KEY,
    experiment_id  INT NOT NULL REFERENCES experiments (experiment_id),
    experiment_key TEXT NOT NULL,
    user_id        TEXT NOT NULL,
    event_type     TEXT NOT NULL CHECK (event_type IN ('conversion', 'revenue', 'refund')),
    value          DOUBLE PRECISION NOT NULL,
    event_time     TIMESTAMPTZ NOT NULL
);

CREATE INDEX idx_assignments_experiment ON assignments (experiment_id);
CREATE INDEX idx_outcomes_user ON outcomes (user_id, event_time);
CREATE INDEX idx_outcomes_experiment ON outcomes (experiment_id, event_type);

